import { useQuery } from '@tanstack/react-query'
import { peopleKeys } from '@/features/employees/api'
import { salesKeys } from '@/features/sales/api/sales'
import { useAppMutation } from '@/hooks/use-app-mutation'
import type { ExpenseSplit, IsoDate } from '@/lib/accounting'
import { unwrap } from '@/lib/errors'
import { formatMonth } from '@/lib/format'
import { fromCents, toCents, type Cents } from '@/lib/money'
import { monthOfDate } from '@/lib/month'
import { supabase } from '@/lib/supabase'
import type { Currency, ExpenseCategory } from '@/types/db'

export interface Expense {
  id: string
  spentOn: IsoDate
  category: ExpenseCategory
  description: string | null
  /** What counts in the accounts (generated by the DB from the original amount). */
  amountAud: Cents
  currency: Currency
  /** Original amount in taka for a BDT expense, otherwise null. */
  bdt: number | null
  /** Taka per A$1, BDT expenses only. */
  fxRate: number | null
  employeeId: string | null
  employeeName: string | null
  /** The sale an employee commission was paid for. */
  saleId: string | null
  saleClientName: string | null
  split: ExpenseSplit
}

export const expenseKeys = { all: ['expenses'] as const }

/** Every expense, newest first. Small enough to fetch whole and filter on the client. */
async function fetchExpenses(): Promise<Expense[]> {
  const rows = unwrap(
    await supabase
      .from('expenses')
      .select(
        `id, spent_on, category, description, original_amount, currency, fx_rate, amount_aud, employee_id, sale_id, split,
         employee:people(name), sale:sales(client_name)`,
      )
      .order('spent_on', { ascending: false })
      .order('created_at', { ascending: false }),
  )
  return rows.map((r) => ({
    id: r.id,
    spentOn: r.spent_on,
    category: r.category,
    description: r.description,
    amountAud: toCents(r.amount_aud),
    currency: r.currency,
    bdt: r.currency === 'BDT' ? Number(r.original_amount) : null,
    fxRate: r.fx_rate === null ? null : Number(r.fx_rate),
    employeeId: r.employee_id,
    employeeName: r.employee?.name ?? null,
    saleId: r.sale_id,
    saleClientName: r.sale?.client_name ?? null,
    split: r.split,
  }))
}

export function useExpensesQuery() {
  return useQuery({ queryKey: expenseKeys.all, queryFn: fetchExpenses })
}

/** Sales embed their commission expense; people count expenses as history. */
const EXPENSE_KEYS = [expenseKeys.all, salesKeys.all, peopleKeys.all]

export interface ExpenseInput {
  /** Set to edit. */
  id?: string
  spentOn: IsoDate
  category: ExpenseCategory
  description: string | null
  currency: Currency
  /** Minor units of `currency` (cents or poisha). */
  amount: number
  /** Required for BDT. */
  fxRate: number | null
  employeeId: string | null
  split: ExpenseSplit
}

async function saveExpense({ id, ...e }: ExpenseInput) {
  const row = {
    spent_on: e.spentOn,
    category: e.category,
    description: e.description,
    currency: e.currency,
    original_amount: fromCents(e.amount),
    fx_rate: e.currency === 'BDT' ? e.fxRate : null,
    employee_id: e.employeeId,
    split: e.split,
  }
  const messages = { '23505': 'This sale already has a commission expense.' }
  unwrap(await (id ? supabase.from('expenses').update(row).eq('id', id) : supabase.from('expenses').insert(row)), messages)
}

export function useSaveExpenseMutation() {
  return useAppMutation({
    mutationFn: saveExpense,
    invalidate: EXPENSE_KEYS,
    success: (_, v) => (v.id ? 'Expense saved' : 'Expense added'),
  })
}

async function deleteExpense(id: string) {
  unwrap(await supabase.from('expenses').delete().eq('id', id))
}

export function useDeleteExpenseMutation() {
  return useAppMutation({ mutationFn: deleteExpense, invalidate: EXPENSE_KEYS, success: 'Expense deleted' })
}

/** One RPC: a Salary expense for each active employee not yet paid that month. Returns how many. */
async function addMonthlySalaries(spentOn: IsoDate): Promise<number> {
  return unwrap(await supabase.rpc('add_monthly_salaries', { p_spent_on: spentOn }))
}

export function useAddMonthlySalariesMutation() {
  return useAppMutation({
    mutationFn: addMonthlySalaries,
    invalidate: EXPENSE_KEYS,
    success: (count, spentOn) => {
      const month = formatMonth(monthOfDate(spentOn))
      return count === 0
        ? `Everyone is already paid for ${month}`
        : `${count} salar${count === 1 ? 'y' : 'ies'} added for ${month}`
    },
  })
}
